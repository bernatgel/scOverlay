#' Example MPNST SingleCellExperiment for the scOverlay vignette
#'
#' A reduced \linkS4class[SingleCellExperiment]{SingleCellExperiment} derived
#' from a single-cell study of peripheral nerve and NF1-associated tumours
#' generated by the package author's research group. The originating study was
#' deposited at the European Genome-phenome Archive (EGAS50000001747).
#'
#' The example was extracted from an independently processed
#' \code{SingleCellExperiment}; the upstream single-cell preprocessing pipeline
#' is not part of scOverlay. Two nerve, two PNF, two ANF and three MPNST samples
#' were selected, with up to 2,500 cells sampled from each. A subset of genes,
#' annotations and embedding coordinates was retained. Original sample IDs were
#' replaced with generic labels (e.g., \code{Nerve1}, \code{PNF1}, \code{ANF1},
#' \code{MPNST1}), including the sample prefixes of cell identifiers. No direct
#' patient identifiers are included.
#'
#' @format A \linkS4class[SingleCellExperiment]{SingleCellExperiment} with a
#' selected set of log-normalized expression values in the \code{logcounts}
#' assay (not raw counts), cell metadata (including sample type, cell types and
#' quality-control metrics), and two-dimensional \code{TSNE} coordinates.
#' \code{UMAP} and \code{PCA} coordinates are retained when available in the
#' processed source object.
#'
#' @source Generated by the package author's research group; originating study
#' deposited at the European Genome-phenome Archive, accession EGAS50000001747,
#' \url{https://ega-archive.org/studies/EGAS50000001747}.
#'
#' @details The reduced example data are distributed with scOverlay under the
#' Artistic-2.0 license. This applies to the reduced packaged example and
#' does not change the access conditions of the original EGA study.
#'
#' @examples
#' data("sce_mpnst_example")
#' sce_mpnst_example
#'
#' @name sce_mpnst_example
#' @docType data
#' @keywords datasets
